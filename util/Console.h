#ifndef HMS_CONSOLE_H
#define HMS_CONSOLE_H

/* ============================================================================
 *  util/Console.h  --  控制台输入输出工具
 * ----------------------------------------------------------------------------
 *  一组与层次无关的输出工具，界面层（menu/）与业务层（service/）都可使用。
 *  放在 util/ 而不是 menu/，是为了不让业务层反向依赖界面层。
 *
 *  解决三类问题：
 *
 *    1. 中文表格对齐
 *       一个汉字在 UTF-8 下占 3 个字节，但在等宽终端里只占 2 列。
 *       printf 的 "%-10s" 是按【字节数】补空格的，用它画含中文的表格
 *       必然参差不齐。所以这里自己算显示宽度再手工补空格。
 *
 *    2. 输入校验
 *       用户可能输入空行、字母、超长内容。"读一个整数并确认读成功"
 *       这件事如果每处都手写，迟早会漏掉某个返回值检查。
 *
 *    3. UTF-8 码点解码
 *       displayWidth 与按宽度截断都依赖它。整个工程只留这一份实现。
 * ==========================================================================*/

/* ==========================================================================
 *  UTF-8 码点解码
 *  从 s[pos] 开始解出一个码点写入 cpOut，返回该字符占用的字节数；
 *  返回 0 表示已到字符串末尾。
 *  非法字节按单字节处理，既保住数据不丢，也不会陷入死循环。
 * ==========================================================================*/
int utf8Decode(const char* s, int pos, unsigned int* cpOut);

/* 字符串在等宽终端里占多少列：ASCII 算 1 列，汉字等算 2 列 */
int displayWidth(const char* s);

/* 按显示宽度打印一个字段，不足 width 列时右侧补空格；
   超宽时按显示宽度截断并加省略号（不能按字节截断，否则汉字会被切半） */
void printField(const char* s, int width);

/* 打印一条横线，形如 "  +----+----+"。widths 给出每列的净宽，
   实际画出的每段长度是 width+2（两侧各留一个空格）。 */
void printSeparator(const int* widths, int count);

/* ==========================================================================
 *  输入
 * ==========================================================================*/

/* 读一行（最多 cap-1 字节），去掉行尾换行。
   返回 true 表示读到了内容（空行也算读到了，此时 buf 为空串）。 */
bool readLine(char* buf, int cap);

/* 读一个整数。成功返回 true 并把值写入 out；
   输入不是合法整数时返回 false（out 不被修改）。
   注意：这里不用 std::atoi —— 它无法区分"输入了 0"和"输入了非法字符"，
   两者都返回 0。 */
bool readInt(int* out);

/* 显示提示语后读一个整数。
   成功返回 true；失败时打印一句提示并返回 false（由调用方决定是否重试）。 */
bool promptInt(const char* prompt, int* out);

/* 显示提示语后读一个整数，并要求它落在 [lo, hi] 内。
   不合规时打印提示并返回 false。 */
bool promptIntInRange(const char* prompt, int lo, int hi, int* out);

/* 显示提示语后读一行文本（可为空）。 */
bool promptLine(const char* prompt, char* buf, int cap);

/* 读一个"是/否"回答。y/Y 为真，n/N 为假，其他输入返回 false 并提示。 */
bool promptYesNo(const char* prompt, bool* out);

/* 显示"按回车继续"并等待 */
void pause();

/* ==========================================================================
 *  输出
 * ==========================================================================*/

/* 打印居中的标题框，如：
       +==============================+
       |   医院门诊预约与智能导诊系统  |
       +==============================+  */
void printTitleBox(const char* title);

/* 打印一条分隔线（固定宽度，用于小节之间） */
void printRule(int width = 70);

#endif /* HMS_CONSOLE_H */
