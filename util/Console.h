#ifndef UTIL_CONSOLE_H
#define UTIL_CONSOLE_H

// 控制台工具。
//
// 放三个与层次无关的工具，界面层和业务层都用得到：
//
//   1. UTF-8 码点解码
//      中文按字节比较会出错（"头痛"和"头晕"的前 3 字节相同），
//      涉及"一个字"的操作都要按码点处理。
//
//   2. 显示宽度
//      算一段文字占几列。一个汉字占 3 个字节但只占 2 列，
//      printf 的 %-10s 是按字节补空格的，直接用会导致含中文的表格
//      参差不齐。
//
//   3. 输入校验
//      读整数、读一行、范围检查，处理空行和非法输入。
//
// 放在中立的 util/ 而不是 menu/，是为了避免业务层反向依赖界面层。
//
// 本模块尚未实现。

#endif
