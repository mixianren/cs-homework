#ifndef DATASTORE_H
#define DATASTORE_H

// 数据仓库。
//
// 职责：集中持有全部数据，并提供按编号和名称的快速查找。
// 业务层只通过本类访问数据，不直接操作各个顺序表。
//
// 为什么要有这一层：
// 如果让导诊、医生查询、排班展示各自去遍历顺序表，那么按编号查医生的
// 逻辑就会散落在好几个文件里。集中到 DataStore 之后，查编号的逻辑只有
// 一份；以后加新模块时也只往这里加数据和方法，已有模块不用改。
//
// 索引与主表的关系：
// 主表是顺序表，存实体本身；索引是哈希表，只存"编号 -> 下标"。
// 实体只有一份，索引只记录位置，所以不存在两份数据不同步的问题。
//
// 一个要注意的前提：索引里存的是下标，不是指针。顺序表扩容时内部数组会
// 重新分配，如果索引存的是指针就会失效；存下标则永远有效。这也是整个
// 工程"实体之间只存编号不存指针"这条约定的由来。
//
// 本模块尚未实现。

#endif
