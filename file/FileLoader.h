#ifndef FILE_FILELOADER_H
#define FILE_FILELOADER_H

// 数据文件加载器。
//
// 职责：把 files/ 目录下的 6 个文本文件解析进 DataStore。
//
// 统一的文件格式约定：
//
//   编码 UTF-8，一行一条记录
//   字段之间用 | 分隔
//   以 # 开头的整行是注释，行内 # 之后也是注释，空行忽略
//   字段两端的空白自动去掉
//
// 加载顺序有依赖，不能打乱：
//
//   症状 -> 科室 -> 医生 -> 排班 -> 患者 -> 症状与科室关联
//
// 因为医生数据里写的是科室名称，要先有科室表才能反查编号；症状与科室
// 的关联同时依赖症状字典和科室表，所以放最后。
//
// 容错原则：坏数据不中断程序。单行解析失败只跳过该行并记一条告警，
// 文件缺失也只记一条告警，只有科室表或医生表为空才返回失败。这样演示
// 时不会因为一个字段写错就整个跑不起来。
//
// 本模块尚未实现。

#endif
