#ifndef SERVICE_TRIAGE_H
#define SERVICE_TRIAGE_H

// 智能导诊。
//
// 题目在实现提示里指出：症状与科室的关联关系可以用加权二部图表示，
// 症状和科室为顶点，关联强度为边权。这里按这个模型来做。
//
// 算法分四步：
//
//   第一步  科室打分
//           对选中的每个症状 s，取它的关联表，对每条边（科室 d，权重 w）：
//               score[d] = score[d] + w
//
//   第二步  折算匹配度
//           match[d] = score[d] / 选中症状数 * 100%
//
//   第三步  排序
//           按 match 降序。得分相同时按科室编号升序，保证输出顺序稳定。
//
//   第四步  取前 K 名
//           默认输出前 5 名，最多 8 名。
//
// 关于权重：如果综合科室（内科、外科）标注了大量常见症状、权重又不
// 压低，那么患者选什么它的分都会很高。本设计在数据文件里把综合科室的
// 权重压到 0.15~0.30，专科给到 0.80~0.95，累加后专科自然排在前面。
// 这是数据层面的调整，不用改代码。
//
// 本模块尚未实现。

#endif
